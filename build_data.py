"""Builds data.js for Office Hours from: the One-on-One guide (.docx), the Zoom practice site's phrases, and tech_phrases.py.
Run: python3 build_data.py"""
import json, os, re, subprocess, docx
from docx.oxml.ns import qn
from tech_phrases import TECH

HERE = os.path.dirname(os.path.abspath(__file__))
GUIDE = os.path.expanduser("~/Desktop/MAI630_Modulo1_Guia_Respuestas_One_on_One.docx")
OLD = os.path.join(HERE, "..", "practica_zoom", "data.js")

# --- the Zoom practice site's sections (kept whole)
old = json.loads(subprocess.check_output(["node", "-e", f"global.window={{}};require({json.dumps(OLD)});console.log(JSON.stringify(window.SECTIONS))"]))
old_by = {s["id"]: s for s in old}

# --- the One-on-One guide
d = docx.Document(GUIDE)
topics, quick, convs = {}, [], []
cur, mode = None, None
for el in d.element.body.iterchildren():
    if el.tag == qn("w:p"):
        t = "".join(x.text or "" for x in el.iter(qn("w:t"))).strip()
        if not t: continue
        if t.startswith("Inicio rápido"): mode = "quick"; continue
        if t.startswith("Mapa de temas"): mode = None; continue
        m = re.match(r"^(\d\d) · (.+)$", t)
        if m and int(m.group(1)) <= 34:
            cur = m.group(1); topics[cur] = {"title": m.group(2), "items": []}; mode = None; continue
        if t.startswith("35 · Conversaciones"): mode = "conv"; continue
        if t.startswith("Fuentes de esta guía"): mode = None; continue
        if mode == "quick" and t.startswith("•"): quick.append(t.lstrip("• ").strip())
        elif mode == "conv":
            m = re.match(r"^(\d)\. (.+)$", t)
            if m: convs.append({"title": m.group(2), "lines": []})
            elif convs: convs[-1]["lines"].append(t)
    elif el.tag == qn("w:tbl") and cur:
        for tr in el.iter(qn("w:tr")):
            cells = ["".join(x.text or "" for x in tc.iter(qn("w:t"))).strip() for tc in tr.iter(qn("w:tc"))]
            if len(cells) >= 2 and cells[0] and not cells[0].startswith("SITUACIÓN"):
                topics[cur]["items"].append({"qes": cells[0], "en": cells[1]})

def topic(num, tid, title=None):
    t = topics[num]
    return {"id": tid, "title": title or t["title"], "items": t["items"]}

def old_topic(sec, tid):
    return next(t for t in old_by[sec]["topics"] if t["id"] == tid)

# Module 1: the guide's topics 03–33, plus the practice site's Module 1 answers added to the closest topic
M1 = [("03", "scope"), ("04", "dates"), ("05", "files"), ("06", "photos"), ("07", "python"), ("08", "venv"), ("09", "verify"),
      ("10", "git"), ("11", "ai"), ("12", "log"), ("13", "functions"), ("14", "notebook"), ("15", "images"), ("16", "grey"),
      ("17", "blur"), ("18", "conv"), ("19", "thresh"), ("20", "edges"), ("21", "sobel"), ("22", "laplacian"), ("23", "canny"),
      ("24", "compare"), ("25", "a11"), ("26", "a11rubric"), ("27", "a12"), ("28", "a12rubric"), ("29", "submit"),
      ("30", "errsetup"), ("31", "errfilters"), ("32", "colab"), ("33", "next")]
MERGE = {"dates": "dates", "setup": "venv", "claude": "ai", "git": "git", "images": "images", "bright": "grey", "blur": "blur",
         "conv": "conv", "thresh": "thresh", "edges": "edges", "canny": "canny", "fail": "compare", "a11": "a11", "a12": "a12"}
m1 = [topic(n, tid) for n, tid in M1]
by = {t["id"]: t for t in m1}
for t in old_by["m1"]["topics"]:
    by[MERGE[t["id"]]]["items"] = by[MERGE[t["id"]]]["items"] + t["items"]

intro = old_by["intro"]
SECTIONS = [
    {"id": "intro", "title": "Reunión 1:1", "sub": "Abrir, guiar y cerrar la reunión", "tag": "Inicio", "topics": [
        old_topic("intro", "open"),
        topic("01", "diagnose", "Diagnóstico inicial"),
        {"id": "key12", "title": "12 frases clave", "items": [{"en": q} for q in quick]},
        old_topic("intro", "notice"), old_topic("intro", "about"), old_topic("intro", "agenda"),
        topic("34", "followup", "Guiar y despedirse"),
        old_topic("intro", "close")]},
    {"id": "tech", "title": "Problemas técnicos", "sub": "Audio, internet, pantalla y Zoom", "tag": "Zoom", "topics": TECH},
    dict(old_by["quick"]),
    {"id": "conv", "title": "Conversaciones", "sub": "Diálogos completos para leer", "tag": "Modelo", "topics": [
        {"id": f"c{i + 1}", "title": c["title"], "items": [{"en": l} for l in c["lines"]]} for i, c in enumerate(convs)]},
    {"id": "m1", "title": "Módulo 1", "sub": "Classical Computer Vision", "tag": "Módulo", "topics": m1},
    old_by["m2"], old_by["m3"], old_by["m4"],
]
out = os.path.join(HERE, "data.js")
open(out, "w").write("/* Generated by build_data.py — edit the sources, not this file. */\nwindow.SECTIONS = "
                     + json.dumps(SECTIONS, ensure_ascii=False, indent=1) + ";\n")
n = sum(len(t["items"]) for s in SECTIONS for t in s.get("topics", []))
print("sections", len(SECTIONS), "topics", sum(len(s.get("topics", [])) for s in SECTIONS), "phrases", n,
      "| guide topics", len(topics), "quick", len(quick), "convs", len(convs))
